export const formatEGP = (minor, { withSymbol = true } = {}) => {
  const value = (Number(minor || 0) / 100).toLocaleString('ar-EG-u-nu-latn', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  return withSymbol ? `${value} ج.م` : value;
};
